export const LANGUAGES = [
  { id: "en", label: "English", locale: "en-GB" },
  { id: "it", label: "Italiano", locale: "it-IT" },
] as const;

export type Language = (typeof LANGUAGES)[number]["id"];

export const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, it };

/** Picks a supported language from the device's preferences, defaulting to English. */
export function detectLanguage(): Language {
  const preferred = typeof navigator !== "undefined" ? navigator.language : "en";
  return LANGUAGES.find((l) => preferred.toLowerCase().startsWith(l.id))?.id ?? "en";
}
